"""Diff of endpoints and models between two Blutter asm trees.

Usage:
  python3 -I tools/diff_versions.py <old_asm_root> <new_asm_root> \
      --old-version 3.18.0 --new-version 3.24.3 [--upstream apitypes.py] \
      [--out tools/out/diff_3.18.0_3.24.3.md]

Reuses endpoint_inventory.scan_root and model_fields.scan_models (no shell-out).
The output is scratch material for the "Since/changed" sections; it is
string-level evidence (a URL or key literal exists in one tree and not in the
other), not a statement about server behavior.
"""
import argparse
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asmparse as A  # noqa: E402
import endpoint_inventory as E  # noqa: E402
import model_fields as M  # noqa: E402


def _by_url(records):
    out = {}
    for r in records:
        d = out.setdefault(r['url'], {'params': set(), 'param_types': set(),
                                      'functions': set(), 'files': set()})
        req = r['_req'] or {}
        d['params'].update(req.get('params', []))
        if req.get('param_type'):
            d['param_types'].add(req['param_type'])
        d['functions'].add(r['function'])
        d['files'].add(r['dart_file'])
    return out


def compute_diff(old_root, new_root, old_ver, new_ver, upstream=None, log=None):
    old_recs, _ = E.scan_root(old_root, log)
    new_recs, _ = E.scan_root(new_root, log)
    old, new = _by_url(old_recs), _by_url(new_recs)
    up = {}
    if upstream and os.path.isfile(upstream):
        eps, _ = A.load_upstream(upstream)
        for k, v in eps.items():
            up.setdefault('/' + v.lstrip('/'), k)
    d = {'upstream': up}
    d['added_endpoints'] = sorted(set(new) - set(old))
    d['removed_endpoints'] = sorted(set(old) - set(new))
    d['changed_params'] = []
    for url in sorted(set(new) & set(old)):
        a, b = old[url], new[url]
        if a['params'] != b['params'] or a['param_types'] != b['param_types']:
            d['changed_params'].append({
                'url': url,
                'added': sorted(b['params'] - a['params']),
                'removed': sorted(a['params'] - b['params']),
                'param_types_added': sorted(b['param_types'] - a['param_types']),
                'param_types_removed': sorted(a['param_types'] - b['param_types']),
            })
    d['new_info'] = {u: {'functions': sorted(v['functions']),
                         'files': sorted(v['files'])} for u, v in new.items()}
    d['old_info'] = {u: {'functions': sorted(v['functions']),
                         'files': sorted(v['files'])} for u, v in old.items()}
    om = M.scan_models(old_root, log)
    nm = M.scan_models(new_root, log)
    mp = M.match_old(nm, om)
    matched_old = set(mp.values())
    d['added_models'] = sorted('%s (%s)' % (k[1], k[0]) for k in nm if k not in mp)
    d['removed_models'] = sorted('%s (%s)' % (k[1], k[0]) for k in om
                                 if k not in matched_old)
    d['changed_fields'] = []
    for k in sorted(nm):
        if k not in mp:
            continue
        of = {f['json_key']: f for f in om[mp[k]]['fields']}
        nf = {f['json_key']: f for f in nm[k]['fields']}
        added = sorted(set(nf) - set(of))
        removed = sorted(set(of) - set(nf))
        retyped = sorted((key, of[key]['dart_type'], nf[key]['dart_type'])
                         for key in set(of) & set(nf)
                         if of[key]['dart_type'] != nf[key]['dart_type'])
        if added or removed or retyped:
            d['changed_fields'].append({'class': k[1], 'dart_file': k[0],
                                        'added': added, 'removed': removed,
                                        'retyped': retyped})
    return d


def render_markdown(d, old_ver, new_ver):
    up = d['upstream']
    L = ['# Diff %s to %s' % (old_ver, new_ver), '',
         'Generated by `tools/diff_versions.py`; string-level evidence only '
         '(a literal exists in one tree and not in the other).', '']
    L.append('## Added endpoints (%d)' % len(d['added_endpoints']))
    L.append('')
    for u in d['added_endpoints']:
        i = d['new_info'].get(u, {})
        L.append('- `%s`%s, %s' % (u, ' (upstream `%s`)' % up[u] if u in up else '',
                                   ', '.join(i.get('functions', []))))
    L += ['', '## Removed endpoints (%d)' % len(d['removed_endpoints']), '']
    for u in d['removed_endpoints']:
        i = d['old_info'].get(u, {})
        L.append('- `%s`%s, %s' % (u, ' (upstream `%s`)' % up[u] if u in up else '',
                                   ', '.join(i.get('functions', []))))
    L += ['', '## Changed params (%d)' % len(d['changed_params']), '']
    for c in d['changed_params']:
        bits = []
        if c['added']:
            bits.append('added ' + ', '.join('`%s`' % x for x in c['added']))
        if c['removed']:
            bits.append('removed ' + ', '.join('`%s`' % x for x in c['removed']))
        if c['param_types_added']:
            bits.append('param_type added ' + ', '.join(c['param_types_added']))
        if c['param_types_removed']:
            bits.append('param_type removed ' + ', '.join(c['param_types_removed']))
        L.append('- `%s`: %s' % (c['url'], '; '.join(bits)))
    L += ['', '## Added models (%d)' % len(d['added_models']), '']
    L += ['- %s' % m for m in d['added_models']]
    L += ['', '## Removed models (%d)' % len(d['removed_models']), '']
    L += ['- %s' % m for m in d['removed_models']]
    L += ['', '## Changed fields (%d)' % len(d['changed_fields']), '']
    for c in d['changed_fields']:
        bits = []
        if c['added']:
            bits.append('added ' + ', '.join('`%s`' % x for x in c['added']))
        if c['removed']:
            bits.append('removed ' + ', '.join('`%s`' % x for x in c['removed']))
        if c['retyped']:
            bits.append('retyped ' + ', '.join(
                '`%s` %s to %s' % t for t in c['retyped']))
        L.append('- `%s` (%s): %s' % (c['class'], c['dart_file'], '; '.join(bits)))
    return '\n'.join(L) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('old_root')
    ap.add_argument('new_root')
    ap.add_argument('--old-version', default='3.18.0')
    ap.add_argument('--new-version', default='3.24.3')
    ap.add_argument('--upstream', default=A.DEFAULT_UPSTREAM)
    ap.add_argument('--out')
    a = ap.parse_args(argv)
    out = a.out or 'tools/out/diff_%s_%s.md' % (a.old_version, a.new_version)
    t0 = time.time()
    d = compute_diff(a.old_root, a.new_root, a.old_version, a.new_version,
                     a.upstream, log=lambda s: print(s, file=sys.stderr))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(render_markdown(d, a.old_version, a.new_version))
    print('added %d / removed %d endpoints, %d changed params, %d added / %d removed '
          'models, %d changed fields -> %s (%.1fs)' % (
              len(d['added_endpoints']), len(d['removed_endpoints']),
              len(d['changed_params']), len(d['added_models']),
              len(d['removed_models']), len(d['changed_fields']), out,
              time.time() - t0))
    return 0


if __name__ == '__main__':
    sys.exit(main())
